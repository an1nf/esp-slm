"""q35 vs llama.cpp parity on a real model."""
import argparse
import os
import subprocess
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import q35_cmp as C

TEXT = ("<|im_start|>user\nExplain in three sentences what a microcontroller is and "
        "what it is used for.<|im_end|>\n<|im_start|>assistant\n")


def run(cmd, log):
    t0 = time.time()
    r = subprocess.run(cmd, capture_output=True, text=True)
    dt = time.time() - t0
    log.write("$ " + " ".join(cmd) + f"\n# {dt:.1f} s, exit {r.returncode}\n")
    if r.stderr:
        log.write(r.stderr[-3000:] + "\n")
    log.flush()
    if r.returncode != 0:
        sys.exit(f"failed: {' '.join(cmd)}\n{r.stderr[-2000:]}")
    return r, dt


def stats(a, b):
    ia, la = C.load(a)
    ib, lb = C.load(b)
    assert (ia == ib).all()
    pa, pb = C.logsoftmax(la), C.logsoftmax(lb)
    kl = (np.exp(pa) * (pa - pb)).sum(-1)
    agree = la.argmax(-1) == lb.argmax(-1)
    rel = np.sqrt(((la - lb) ** 2).mean(-1)) / np.sqrt((la ** 2).mean(-1))
    return agree, kl, rel


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model", required=True)
    ap.add_argument("--llama", required=True, help="llama_logits binary")
    ap.add_argument("--q35", default="build/q35")
    ap.add_argument("--gen", type=int, default=64)
    ap.add_argument("--text", default=TEXT)
    ap.add_argument("--ids", default=None, help="token ids instead of text")
    ap.add_argument("--threads", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--out", default="results")
    ap.add_argument("--chunk", type=int, default=16)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    tag = os.path.splitext(os.path.basename(a.model))[0]
    P = lambda n: os.path.join(a.out, f"{tag}.{n}.bin")
    log = open(os.path.join(a.out, f"{tag}.log"), "w")

    info = subprocess.run([a.q35, "info", a.model], capture_output=True, text=True)
    if info.returncode:
        sys.exit(f"q35 cannot load the model:\n{info.stderr}")
    print(info.stdout + info.stderr)
    print("1/4 llama.cpp, exact config (FA off, KV f32)", flush=True)
    src = ["--ids", a.ids] if a.ids else ["--text", a.text]
    r, _ = run([a.llama, a.model, P("ll_exact"), *src, "--gen", str(a.gen),
                "--fa", "off", "--kv", "f32", "--threads", str(a.threads)], log)
    err = r.stderr
    text = err[err.rfind("<<<\n") + 4:err.rfind(">>>")].strip() if "<<<" in err else "(no vocab)"
    ids, _ = C.load(P("ll_exact"))
    ids_s = ",".join(str(int(t)) for t in ids)
    n = len(ids)
    print(f"    {n} positions ({n - a.gen} prompt + {a.gen} generated)")
    print("    llama.cpp, default config (FA, KV f16)", flush=True)
    run([a.llama, a.model, P("ll_default"), "--ids", ids_s, "--threads", str(a.threads)], log)

    print("2/4 q35 with KV f32 and KV f16", flush=True)
    _, t_q = run([a.q35, "dump", a.model, P("q_exact"), "--ids", ids_s, "--kv", "f32",
                  "--ctx", str(n + 8), "--chunk", str(a.chunk)], log)
    run([a.q35, "dump", a.model, P("q_f16"), "--ids", ids_s, "--kv", "f16",
         "--ctx", str(n + 8), "--chunk", str(a.chunk)], log)

    print("3/4 q35 with GDN state in f16, bf16 and int8", flush=True)
    for st in ("f16", "bf16", "int8"):
        run([a.q35, "dump", a.model, P(f"q_state_{st}"), "--ids", ids_s, "--kv", "f32",
             "--state", st, "--ctx", str(n + 8), "--chunk", str(a.chunk)], log)

    print("4/4 q35 decode speed (16 tokens, one thread)", flush=True)
    r, _ = run([a.q35, "run", a.model, "--ids", ids_s, "--gen", "16", "--top", "1",
                "--ctx", str(n + 24), "--chunk", str(a.chunk)], log)
    speed = [l for l in r.stderr.splitlines() if "tokens in" in l]

    rows = []
    pairs = [("q35 exact vs llama.cpp exact", "ll_exact", "q_exact"),
             ("q35 KV f16 vs llama.cpp default", "ll_default", "q_f16"),
             ("llama.cpp default vs llama.cpp exact (own noise)", "ll_exact", "ll_default"),
             ("GDN state f16 vs f32 (q35)", "q_exact", "q_state_f16"),
             ("GDN state bf16 vs f32 (q35)", "q_exact", "q_state_bf16"),
             ("GDN state int8 per row vs f32 (q35)", "q_exact", "q_state_int8")]
    res = {}
    for name, x, y in pairs:
        ag, kl, rel = stats(P(x), P(y))
        res[(x, y)] = (ag, kl)
        rows.append(f"| {name} | {ag.sum()}/{len(ag)} ({100 * ag.mean():.1f} %) | "
                    f"{kl.mean():.2e} | {np.median(kl):.2e} | {kl.max():.2e} | {rel.mean():.2e} |")
    ag, kl = res[("ll_exact", "q_exact")]
    p1 = ag.mean() >= 0.95
    p2 = kl.mean() <= 0.01
    rep = [f"# q35 parity, {tag}", "", "```", (info.stdout + info.stderr).strip(), "```", "",
           f"Sequence: {n} positions; text generated by llama.cpp (greedy):", "",
           "```", text, "```", "",
           "| Comparison | argmax equal | KL mean | KL median | KL max | rel rms |",
           "|---|---|---|---|---|---|", *rows, "",
           f"- P1 (argmax >= 95 %): {'PASS' if p1 else 'FAIL'}",
           f"- P2 (mean KL <= 0.01 nats): {'PASS' if p2 else 'FAIL'}", "",
           f"q35 dump (KV f32, chunks of {a.chunk}): {t_q:.1f} s for {n} positions.", "",
           "q35 speed:", "", "```", *speed, "```", ""]
    txt = "\n".join(rep)
    with open(os.path.join(a.out, f"{tag}.md"), "w") as f:
        f.write(txt)
    print()
    print(txt)


if __name__ == "__main__":
    main()
